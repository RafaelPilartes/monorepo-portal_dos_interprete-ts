#!/usr/bin/env python3
"""The error catalog lives in docs/plan/api.md §2 (the single source, architecture.md §6).

    python3 scripts/error_catalog.py --write   regenerate packages/core/src/errors/catalog.ts
    python3 scripts/error_catalog.py --check   exit 1 if the TypeScript catalog differs from api.md

verify.py runs the check, so the catalog cannot drift from the document.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API_DOC = ROOT / "docs" / "plan" / "api.md"
TARGET = ROOT / "packages" / "core" / "src" / "errors" / "catalog.ts"
ROW = re.compile(r"^\| `([A-Z_]+)` \| (\d{3}) \| (.*?) \| (.*?) \|\s*$")


def parse(text: str) -> list[dict]:
    section = text[text.index("## 2. Erros"): text.index("## 3. Sistema")]
    entries = []
    for line in section.splitlines():
        match = ROW.match(line)
        if not match:
            continue
        code, status, message, field = match.groups()
        field = field.strip()
        field_value = None
        if field.startswith("`") and field.endswith("`"):
            field_value = field.strip("`")
        entries.append({"code": code, "status": int(status), "message": message.strip(), "field": field_value})
    return entries


def render(entries: list[dict]) -> str:
    lines = [
        "// GENERATED by scripts/error_catalog.py from docs/plan/api.md §2. Do not edit by hand:",
        "// change api.md and run `python3 scripts/error_catalog.py --write`.",
        "",
        "export const ERROR_CATALOG = {",
    ]
    for entry in entries:
        field = "null" if entry["field"] is None else json.dumps(entry["field"])
        lines.append(
            f"  {entry['code']}: {{ status: {entry['status']}, message: {json.dumps(entry['message'], ensure_ascii=False)}, field: {field} }},"
        )
    lines += ["} as const", "", "export type ErrorCode = keyof typeof ERROR_CATALOG", ""]
    return "\n".join(lines)


def main() -> int:
    expected = render(parse(API_DOC.read_text(encoding="utf-8")))
    if "--write" in sys.argv:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(expected, encoding="utf-8")
        print(f"wrote {TARGET.relative_to(ROOT)}")
        return 0
    current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
    if current != expected:
        print(f"{TARGET.relative_to(ROOT)} differs from docs/plan/api.md §2; run scripts/error_catalog.py --write")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
