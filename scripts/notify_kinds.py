#!/usr/bin/env python3
"""Generate packages/db/seed/0001-notify-kinds.sql from the catalog in docs/plan/specs/notifications.md.

R-NOT-01: the list of notices lives in one place (the spec); notify.kinds is loaded from it.

  python3 scripts/notify_kinds.py --write   regenerate the seed file
  python3 scripts/notify_kinds.py --check   exit 1 when the seed file differs from the spec
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SPEC = Path("docs/plan/specs/notifications.md")
TARGET = Path("packages/db/seed/0001-notify-kinds.sql")
ROW = re.compile(r"^\| `([a-z][a-z0-9_]*)` \|[^|]*\|[^|]*\| ([^|]+) \|$")
CHANNEL_NAMES = {"P": "portal", "E": "email"}


def channels_of(cell: str) -> list[str]:
    """'P, E' → portal, email. A note in brackets may add a channel: 'P (E no máximo ...)'."""
    base, _, note = cell.strip().partition("(")
    letters = [token.strip() for token in base.split(",") if token.strip()]
    if note.strip().startswith("E "):
        letters.append("E")
    unknown = [letter for letter in letters if letter not in CHANNEL_NAMES]
    if unknown or not letters:
        raise ValueError(f"cannot read channels from {cell!r}")
    return [name for key, name in CHANNEL_NAMES.items() if key in letters]


def parse(text: str) -> list[tuple[str, list[str]]]:
    section = text[text.find("## Catálogo"): text.find("## Ecrãs")]
    return [(m.group(1), channels_of(m.group(2))) for line in section.splitlines() if (m := ROW.match(line))]


def catalog_rows(text: str) -> int:
    section = text[text.find("## Catálogo"): text.find("## Ecrãs")]
    return sum(1 for line in section.splitlines() if line.startswith("| `"))


def render(kinds: list[tuple[str, list[str]]]) -> str:
    values = ",\n".join(
        f"  ('{code}', ARRAY[{', '.join(repr(c) for c in channels)}])" for code, channels in kinds
    )
    return (
        "-- Generated by scripts/notify_kinds.py from docs/plan/specs/notifications.md (R-NOT-01).\n"
        "-- Never edit by hand: change the spec and run python3 scripts/notify_kinds.py --write.\n"
        "INSERT INTO notify.kinds (code, channels) VALUES\n"
        f"{values}\n"
        "ON CONFLICT (code) DO UPDATE SET channels = EXCLUDED.channels;\n"
    )


def expected(root: Path) -> str:
    text = (root / SPEC).read_text(encoding="utf-8")
    kinds = parse(text)
    if len(kinds) != catalog_rows(text):
        raise ValueError(f"{catalog_rows(text) - len(kinds)} catalog row(s) in {SPEC} do not parse")
    return render(kinds)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = expected(REPO_ROOT)
    target = REPO_ROOT / TARGET
    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        print(f"wrote {TARGET}")
        return 0
    if target.is_file() and target.read_text(encoding="utf-8") == content:
        return 0
    print(f"{TARGET} differs from {SPEC}; run python3 scripts/notify_kinds.py --write")
    return 1


if __name__ == "__main__":
    sys.exit(main())
