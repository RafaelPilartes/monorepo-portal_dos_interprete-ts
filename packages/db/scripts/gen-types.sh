#!/usr/bin/env bash
# Generates packages/db-types/src/database.ts from the applied database (architecture.md §5).
#   gen-types.sh            write the file
#   gen-types.sh <path>     write somewhere else (db:verify compares it with the committed file)
source "$(dirname "$0")/lib.sh"
target="${1:-$REPO_ROOT/packages/db-types/src/database.ts}"
instance_running || die "a base local não está a correr (pnpm db:up)."
tmp="$(mktemp)"
errors="$(mktemp)"
trap 'rm -f -- "$tmp" "$errors"' EXIT
{
  echo "// Generated by packages/db/scripts/gen-types.sh from the applied database. Never edit by hand."
  supabase_cli gen types typescript --local --schema "$EXPOSED_SCHEMAS" 2>"$errors"
} > "$tmp" || { cat "$errors" >&2; die "a geração dos tipos falhou (acima)."; }
node "$DB_ROOT/scripts/format-ts.mjs" "$tmp"
cp "$tmp" "$target"
say "tipos escritos em ${target#"$REPO_ROOT"/}"
